export const ideas: readonly Idea[] = canonicalIdeas.map(([number, nameEn, name]) => ({
  id: canonicalIdeaId(name),
  number,
  name,
  slug: canonicalizeIdeaSlug(name),
  nameEn,
  slugEn: canonicalizeIdeaSlug(nameEn),
  provenance: {
    sourceId: "source:syntopicon-canonical-ideas-list",
    layer: "derived-structure",
  },
}));

/** URL canônica da Grande Ideia: /ideias/{número}-{slugEn} */
export function ideaUrl(idea: Idea): string {
  return `/ideias/${idea.number}-${idea.slugEn}`;
}

export function ideaByCanonicalUrlSlug(urlSlug: string): Idea | undefined {
  return ideas.find((idea) => `${idea.number}-${idea.slugEn}` === urlSlug);
}
